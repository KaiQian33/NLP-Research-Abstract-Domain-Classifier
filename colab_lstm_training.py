import os, re, time, shutil
import numpy as np
import pandas as pd
import joblib

from sklearn.model_selection import train_test_split, GridSearchCV
from sklearn.preprocessing import LabelEncoder
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.tree import DecisionTreeClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score

import nltk
for pkg in ["punkt", "punkt_tab", "stopwords", "wordnet", "omw-1.4"]:
    try:
        nltk.download(pkg, quiet=True)
    except Exception:
        pass
from nltk.tokenize import word_tokenize
from nltk.corpus import stopwords
from nltk.stem import WordNetLemmatizer

SEED = 42
np.random.seed(SEED)
MODEL_DIR = "models"
os.makedirs(MODEL_DIR, exist_ok=True)

_stop_words = set(stopwords.words("english"))
_lemmatizer = WordNetLemmatizer()

def preprocess_text(text):
    text = str(text).lower()
    text = re.sub(r"[^a-zA-Z\s]", "", text)
    tokens = word_tokenize(text)
    tokens = [_lemmatizer.lemmatize(w) for w in tokens if w not in _stop_words and len(w) > 2]
    return " ".join(tokens)

# ---- 1. Load & clean ----
# >>> Change this if your uploaded file has a different name <<<
DATA_PATH = "Data.xlsx"

df = pd.read_excel(DATA_PATH)
df = df.dropna(subset=["Abstract", "Domain"]).drop_duplicates()
df["keywords"] = df["keywords"].fillna("") if "keywords" in df.columns else ""
print(f"Loaded {df.shape}")

# ---- 2. Preprocess ----
print("Preprocessing abstracts...")
df["Processed_Abstract"] = df["Abstract"].apply(preprocess_text)
df["Processed_Keywords"] = df["keywords"].apply(preprocess_text)

# ---- 3. Labels & split ----
label_encoder = LabelEncoder()
df["Domain_Label"] = label_encoder.fit_transform(df["Domain"])

X_train_text, X_test_text, X_train_kw, X_test_kw, y_train, y_test = train_test_split(
    df["Processed_Abstract"], df["Processed_Keywords"], df["Domain_Label"].values,
    test_size=0.3, random_state=SEED, stratify=df["Domain_Label"].values
)

tfidf = TfidfVectorizer(max_features=5000, min_df=5, max_df=0.8)
X_train_tfidf = tfidf.fit_transform(X_train_text)
X_test_tfidf = tfidf.transform(X_test_text)

results = []
def evaluate(name, model, X_test, y_test):
    pred = model.predict(X_test)
    results.append({
        "Model": name,
        "Accuracy": accuracy_score(y_test, pred),
        "Precision": precision_score(y_test, pred, average="weighted", zero_division=0),
        "Recall": recall_score(y_test, pred, average="weighted", zero_division=0),
        "F1": f1_score(y_test, pred, average="weighted", zero_division=0),
    })

# ---- 4. Decision Tree ----
print("Training Decision Tree (GridSearch)...")
param_grid = {"criterion": ["gini", "entropy"], "max_depth": [20, 30, None], "min_samples_split": [2, 5]}
grid = GridSearchCV(DecisionTreeClassifier(random_state=SEED), param_grid, cv=5, scoring="f1_weighted", n_jobs=-1)
grid.fit(X_train_tfidf, y_train)
dt = grid.best_estimator_
print("Best DT params:", grid.best_params_)
evaluate("Decision Tree", dt, X_test_tfidf, y_test)

# ---- 5. Logistic Regression ----
print("Training Logistic Regression...")
lr = LogisticRegression(max_iter=1000, solver="lbfgs", random_state=SEED, n_jobs=-1)
lr.fit(X_train_tfidf, y_train)
evaluate("Logistic Regression", lr, X_test_tfidf, y_test)

# ---- 6. Save sklearn artifacts ----
joblib.dump(tfidf, os.path.join(MODEL_DIR, "tfidf.joblib"))
joblib.dump(label_encoder, os.path.join(MODEL_DIR, "label_encoder.joblib"))
joblib.dump(dt, os.path.join(MODEL_DIR, "dt_model.joblib"))
joblib.dump(lr, os.path.join(MODEL_DIR, "lr_model.joblib"))

# ============================================================================
# 7. BiLSTM — the part that needed GPU
# ============================================================================
print("\nTraining BiLSTM (this uses the GPU)...")

import tensorflow as tf
from tensorflow.keras.preprocessing.text import Tokenizer
from tensorflow.keras.preprocessing.sequence import pad_sequences
from tensorflow.keras.models import Model
from tensorflow.keras.layers import Input, Embedding, LSTM, Bidirectional, Dense, Dropout
from tensorflow.keras.callbacks import EarlyStopping
from sklearn.utils.class_weight import compute_class_weight

tf.random.set_seed(SEED)

ABS_MAX_WORDS, ABS_MAX_LENGTH = 10000, 200
abs_tokenizer = Tokenizer(num_words=ABS_MAX_WORDS)
abs_tokenizer.fit_on_texts(X_train_text)

X_train_seq = pad_sequences(abs_tokenizer.texts_to_sequences(X_train_text), maxlen=ABS_MAX_LENGTH, padding="post", truncating="post")
X_test_seq = pad_sequences(abs_tokenizer.texts_to_sequences(X_test_text), maxlen=ABS_MAX_LENGTH, padding="post", truncating="post")

n_classes = len(label_encoder.classes_)
classes_present = np.unique(y_train)
weights = compute_class_weight("balanced", classes=classes_present, y=y_train)
class_weight = dict(zip(classes_present, weights))

inp = Input(shape=(ABS_MAX_LENGTH,))
x = Embedding(ABS_MAX_WORDS, 128, mask_zero=True)(inp)
x = Bidirectional(LSTM(128))(x)
x = Dense(64, activation="relu")(x)
x = Dropout(0.5)(x)
out = Dense(n_classes, activation="softmax")(x)
lstm_model = Model(inp, out)
lstm_model.compile(optimizer="adam", loss="sparse_categorical_crossentropy", metrics=["accuracy"])
lstm_model.summary()

lstm_model.fit(
    X_train_seq, y_train,
    epochs=10, batch_size=32, validation_split=0.2, class_weight=class_weight,
    callbacks=[EarlyStopping(monitor="val_loss", patience=2, restore_best_weights=True)],
    verbose=1,
)

pred = np.argmax(lstm_model.predict(X_test_seq), axis=1)
evaluate("BiLSTM (Abstract only)", type("M", (), {"predict": lambda self, X: pred})(), X_test_seq, y_test)

lstm_model.save(os.path.join(MODEL_DIR, "lstm_model.keras"))
joblib.dump(abs_tokenizer, os.path.join(MODEL_DIR, "abs_tokenizer.joblib"))
joblib.dump({"max_length": ABS_MAX_LENGTH}, os.path.join(MODEL_DIR, "lstm_config.joblib"))

# ---- 8. Save comparison table ----
summary_df = pd.DataFrame(results).sort_values("F1", ascending=False)
summary_df.to_csv(os.path.join(MODEL_DIR, "model_comparison_results.csv"), index=False)
print("\n", summary_df.to_string(index=False))

# ---- 9. Zip everything for download ----
shutil.make_archive("models", "zip", MODEL_DIR)
print("\n✅ Done! Download 'models.zip' from the left sidebar (Files icon).")